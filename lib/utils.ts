import { clsx, type ClassValue } from 'clsx';
import { twMerge } from 'tailwind-merge';

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

/** Tint a hex color with an alpha — for "light background of a semantic color" treatments
 * (status pills, urgent-row backgrounds) that Tailwind's opacity-modifier classes (`bg-x/5`)
 * don't compile reliably in this project's NativeWind setup. */
export function hexToRgba(hex: string, alpha: number): string {
  const r = parseInt(hex.slice(1, 3), 16);
  const g = parseInt(hex.slice(3, 5), 16);
  const b = parseInt(hex.slice(5, 7), 16);
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}
